// Image-job fixtures (M4 design §5): an approved storyboard with scenes, a mock image model, a
// stored reference image, and image jobs created exactly as the API does (intent first).
import { randomUUID } from 'node:crypto';

import {
  activeImageJobKey,
  executionKey,
  sceneContentHash,
  type ImageJobInput,
} from '@acf/content-domain';
import type { PrismaClient } from '@acf/database';
import { assetObjectKey, S3ObjectStore, sha256Hex, uuidv7, type ObjectStore } from '@acf/storage';
import { solidPng } from '@acf/storage/testing';

import type { World } from './fixtures.js';

/** The real object store (SeaweedFS locally and in CI) with the worker test bucket. */
export function testStore(): ObjectStore {
  const need = (key: string) => {
    const value = process.env[key];
    if (!value)
      throw new Error(`${key} is not set (storage tests need SeaweedFS; see .env.example)`);
    return value;
  };
  return new S3ObjectStore({
    endpoint: need('S3_ENDPOINT'),
    region: process.env['S3_REGION'] ?? 'us-east-1',
    bucket: 'acf-test-worker',
    accessKeyId: need('S3_ACCESS_KEY_ID'),
    secretAccessKey: need('S3_SECRET_ACCESS_KEY'),
    forcePathStyle: true,
  });
}

export interface ImageWorld {
  readonly imageModelId: string;
  readonly storyboardVersionId: string;
  readonly sceneIds: readonly string[];
  readonly referenceAssetId: string;
}

/** Approved script + storyboard (2 scenes), a mock image model (n ≤ 2), a stored reference. */
export async function createImageWorld(
  prisma: PrismaClient,
  store: ObjectStore,
  w: World,
): Promise<ImageWorld> {
  const provider = await prisma.aiProvider.findUniqueOrThrow({ where: { key: 'mock' } });
  const model =
    (await prisma.aiModel.findFirst({
      where: { providerId: provider.id, modelKey: 'mock/solid-image' },
    })) ??
    (await prisma.aiModel.create({
      data: {
        providerId: provider.id,
        modelKey: 'mock/solid-image',
        displayName: 'Mock images',
        qualityTier: 'premium',
        status: 'enabled',
        supportedParameters: ['aspect_ratio', 'input_references', 'n', 'resolution', 'seed'],
        imageConstraints: {
          maxImages: 2,
          maxReferences: 4,
          aspectRatios: ['9:16', '1:1', '16:9'],
          resolutions: ['1K', '2K'],
          seed: true,
        },
        capabilities: { create: { capability: 'image_generation' } },
        prices: {
          create: {
            metric: 'output_images',
            unitPrice: '0.01',
            sourceValue: '0.01',
            effectiveFrom: new Date('2026-01-01T00:00:00Z'),
            source: 'manual_estimate',
            sourceUrl: 'urn:acf:test',
            capturedAt: new Date('2026-01-01T00:00:00Z'),
          },
        },
      },
    }));

  // A text job only as the "generated by" link of the script and storyboard versions.
  const run = await prisma.productionRun.create({
    data: { projectId: w.projectId, contentItemId: w.contentItemId, requestedById: w.userId },
  });
  const textJob = await prisma.generationJob.create({
    data: {
      projectId: w.projectId,
      contentItemId: w.contentItemId,
      productionRunId: run.id,
      kind: 'storyboard_generation',
      activeKey: `${w.contentItemId}:storyboard_generation`,
      idempotencyKey: randomUUID(),
      executionKey: 'f'.repeat(64),
      input: {},
      previousContentStatus: 'script_review',
      promptTemplateId: 'storyboard.v1',
      modelId: w.modelId,
      requestedById: w.userId,
    },
  });
  const script = await prisma.scriptVersion.create({
    data: {
      projectId: w.projectId,
      contentItemId: w.contentItemId,
      version: 1,
      source: 'generated',
      generationJobId: textJob.id,
      schemaVersion: 1,
      content: {},
    },
  });
  await prisma.scriptVersion.update({
    where: { id: script.id },
    data: { status: 'approved', reviewedById: w.userId, reviewedAt: new Date() },
  });
  await prisma.contentItem.update({
    where: { id: w.contentItemId },
    data: { approvedScriptVersionId: script.id },
  });
  const storyboard = await prisma.storyboardVersion.create({
    data: {
      projectId: w.projectId,
      contentItemId: w.contentItemId,
      scriptVersionId: script.id,
      version: 1,
      source: 'generated',
      generationJobId: textJob.id,
      schemaVersion: 1,
      totalDurationSeconds: 30,
    },
  });
  const sceneIds: string[] = [];
  for (const n of [1, 2]) {
    const scene = await prisma.storyboardScene.create({
      data: {
        projectId: w.projectId,
        storyboardVersionId: storyboard.id,
        sceneNumber: n,
        durationSeconds: 15,
        shotType: 'medium',
        cameraAngle: 'eye-level',
        cameraMovement: 'static',
        characterAction: 'presents the gadget',
        visualDescription: `Scene ${String(n)} on a desk`,
        imagePrompt: `Gadget ${String(n)} on a tidy desk`,
        videoPrompt: 'slow push in',
        negativePrompt: 'text',
        voiceOverSegment: '',
        onScreenText: '',
        characterVersionId: w.characterVersionId,
      },
    });
    sceneIds.push(scene.id);
  }
  await prisma.storyboardVersion.update({
    where: { id: storyboard.id },
    data: { status: 'approved', reviewedById: w.userId, reviewedAt: new Date() },
  });
  await prisma.contentItem.update({
    where: { id: w.contentItemId },
    data: { approvedStoryboardVersionId: storyboard.id, status: 'storyboard_review' },
  });

  // A reference image whose bytes are really in storage.
  const bytes = solidPng(32, 32, 9);
  const referenceAssetId = uuidv7();
  const key = assetObjectKey({
    projectId: w.projectId,
    assetId: referenceAssetId,
    sha256Hex: sha256Hex(bytes),
    mimeType: 'image/png',
  });
  await store.putIfAbsent(key, bytes, { contentType: 'image/png', sha256Hex: sha256Hex(bytes) });
  await prisma.asset.create({
    data: {
      id: referenceAssetId,
      projectId: w.projectId,
      assetType: 'reference',
      sourceType: 'upload',
      storageKey: key,
      mimeType: 'image/png',
      sizeBytes: BigInt(bytes.byteLength),
      checksumSha256: sha256Hex(bytes),
      width: 32,
      height: 32,
      createdById: w.userId,
    },
  });
  return { imageModelId: model.id, storyboardVersionId: storyboard.id, sceneIds, referenceAssetId };
}

/** Image job input for one scene of the image world. */
export async function imageInput(
  prisma: PrismaClient,
  iw: ImageWorld,
  sceneId: string,
  overrides: Partial<ImageJobInput> = {},
): Promise<ImageJobInput> {
  const s = await prisma.storyboardScene.findUniqueOrThrow({ where: { id: sceneId } });
  const scene = {
    sceneNumber: s.sceneNumber,
    shotType: s.shotType,
    cameraAngle: s.cameraAngle,
    visualDescription: s.visualDescription,
    imagePrompt: s.imagePrompt,
    negativePrompt: s.negativePrompt,
    characterVersionId: s.characterVersionId,
    environmentVersionId: s.environmentVersionId,
  };
  const references = [{ assetId: iw.referenceAssetId, role: 'character' as const }];
  return {
    storyboardVersionId: iw.storyboardVersionId,
    sceneId,
    scene,
    characterName: 'Khánh',
    environmentName: null,
    aspectRatio: '9:16',
    resolution: '2K',
    count: 1,
    seed: 7,
    references,
    sceneHash: sceneContentHash({
      scene,
      aspectRatio: '9:16',
      referenceAssetIds: references.map((r) => r.assetId),
    }),
    zeroDataRetention: false,
    qualityTier: 'balanced',
    ...overrides,
  };
}

/** Creates one run with an image job per input, and moves the content status (API M4d). */
export async function createImageJobs(
  prisma: PrismaClient,
  w: World,
  iw: ImageWorld,
  inputs: readonly ImageJobInput[],
): Promise<string[]> {
  return prisma.$transaction(async (tx) => {
    const item = await tx.contentItem.findUniqueOrThrow({ where: { id: w.contentItemId } });
    const run = await tx.productionRun.create({
      data: { projectId: w.projectId, contentItemId: w.contentItemId, requestedById: w.userId },
    });
    const ids: string[] = [];
    for (const input of inputs) {
      const job = await tx.generationJob.create({
        data: {
          projectId: w.projectId,
          contentItemId: w.contentItemId,
          productionRunId: run.id,
          kind: 'image_generation',
          storyboardSceneId: input.sceneId,
          activeKey: activeImageJobKey(input.sceneId),
          idempotencyKey: randomUUID(),
          executionKey: executionKey({
            kind: 'image_generation',
            contentItemId: w.contentItemId,
            brief: { sceneHash: input.sceneHash, count: input.count },
            inputVersionIds: input.references.map((r) => r.assetId),
            promptTemplateId: 'image.v1',
            modelId: iw.imageModelId,
          }),
          input,
          previousContentStatus: item.status,
          promptTemplateId: 'image.v1',
          modelId: iw.imageModelId,
          requestedById: w.userId,
        },
      });
      await tx.jobEvent.create({
        data: {
          projectId: w.projectId,
          jobId: job.id,
          toStatus: 'queued',
          attempt: 0,
          detail: { type: 'created' },
        },
      });
      ids.push(job.id);
    }
    await tx.contentItem.update({
      where: { id: w.contentItemId },
      data: { status: 'generating_assets' },
    });
    return ids;
  });
}
